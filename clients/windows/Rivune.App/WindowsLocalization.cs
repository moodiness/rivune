    internal static string Format(string key, string? languageTag, params object?[] arguments) =>
        string.Format(CultureInfo.CurrentCulture, Translate(key, languageTag), arguments);

    internal static string NormalizeLanguage(string? languageTag)
    {
        if (string.IsNullOrWhiteSpace(languageTag)) return "en";
        if (languageTag.StartsWith("fr", StringComparison.OrdinalIgnoreCase)) return "fr";
        if (languageTag.StartsWith("es", StringComparison.OrdinalIgnoreCase)) return "es";
        if (languageTag.StartsWith("de", StringComparison.OrdinalIgnoreCase)) return "de";
        if (languageTag.StartsWith("it", StringComparison.OrdinalIgnoreCase)) return "it";
        if (languageTag.StartsWith("pt", StringComparison.OrdinalIgnoreCase)) return "pt-BR";
        return "en";
    }

